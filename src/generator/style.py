"""블로그 문체 규칙과 시스템 프롬프트 조립.

문체는 지어내지 않고 `blog-post.md`(실제로 쓴 글)에서 뽑아냈다.
톤을 바꾸고 싶으면 STYLE_RULES를 고치거나, blog-post.md를 다른 글로 교체하면 된다.
"""

import os

from src.config import STYLE_SAMPLE_PATH

# blog-post.md를 읽어 관찰한 특징. 예시 글과 함께 프롬프트에 들어간다.
STYLE_RULES = """## 문체 규칙

- 존댓말. "~습니다"와 "~해요"를 섞어 쓰되, 딱딱해지면 "~해요" 쪽으로 푼다.
- 구어체 종결을 적극적으로 쓴다: "~하더라고요", "~거든요", "~잖아요", "~인데요".
- 한 문단은 2~3줄. 길어지면 끊어서 개행한다. 벽 같은 문단 금지.
- 큰 흐름이 바뀌는 곳마다 `---` 구분선을 넣는다.
- 소제목은 `##`, 단계 설명은 `### 1단계: ...` 형태를 쓴다.
- 핵심 문장은 **굵게** 강조한다. 한 문단에 하나까지만.
- 숫자는 구체적으로 쓴다. "많이"가 아니라 "147건", "약 30분", "1년이면 120시간".
- 잘 안 된 이야기를 빼지 않는다. 막혔던 지점과 어떻게 풀었는지를 그대로 쓴다.
- 독자에게 말을 건다: "~하시면 돼요", "~아닐까요?", "보여드릴게요".
- 본문에 이모지를 쓰지 않는다.

## 쓰지 않는 표현

- "~인 것 같습니다" 같은 얼버무리는 추측
- "바야흐로", "여러분!" 같은 과장된 도입
- 굳이 영어로 쓸 필요 없는 말의 영어 표기
- "놀랍게도", "충격적인" 같은 낚시성 수식어
- AI가 썼다는 티가 나는 정리형 마무리 ("결론적으로", "요약하자면")

## 구조

1. 왜 이걸 하게 됐는지 (겪은 불편에서 시작)
2. 결과물 먼저 보여주기
3. 과정을 단계로 나눠 설명
4. 막혔던 지점과 해결
5. 비용/시간처럼 독자가 궁금해할 실무 정보
6. 담백한 마무리 (교훈 설교하지 않기)

주제에 따라 이 구조는 조정해도 된다. 다만 "결과 먼저, 과정은 단계로"는 유지한다.
"""

_OUTPUT_CONTRACT = """## 출력 형식

아래 형식을 정확히 지켜라. 앞뒤에 다른 말을 붙이지 마라.

---
제목: (25자 이내, 낚시성 없이 내용을 그대로 드러내는 제목)
태그: (쉼표로 구분한 5~10개. # 없이 단어만)
---

(본문 마크다운)

본문은 마크다운으로 쓴다. 이미지 자리는 `[사진]`이라고만 적어라.
"""


def _read_style_sample():
    """문체 예시 글을 읽는다. 없으면 규칙만으로 진행한다."""
    if not os.path.exists(STYLE_SAMPLE_PATH):
        print(f"[WARN] 문체 예시 파일 없음: {STYLE_SAMPLE_PATH}. 규칙만으로 작성합니다.")
        return ""

    try:
        with open(STYLE_SAMPLE_PATH, encoding="utf-8") as f:
            return f.read()
    except OSError as e:
        print(f"[WARN] 문체 예시 파일을 읽지 못했습니다: {e}")
        return ""


def build_system_prompt():
    """문체 규칙 + 예시 글로 시스템 프롬프트를 만든다.

    호출할 때마다 같은 문자열이 나와야 프롬프트 캐시가 적중한다.
    날짜·랜덤값 같은 변하는 값을 절대 넣지 마라.
    """
    sample = _read_style_sample()

    parts = [
        "너는 신요한의 네이버 블로그 글을 대신 쓴다.",
        "아래 문체 규칙과 예시 글의 톤을 그대로 따라라. 새로운 톤을 만들어내지 마라.",
        "",
        STYLE_RULES,
    ]

    if sample:
        parts += [
            "",
            "## 예시 글 (이 톤을 따라라)",
            "",
            "<예시>",
            sample,
            "</예시>",
        ]

    parts += ["", _OUTPUT_CONTRACT]

    return "\n".join(parts)
